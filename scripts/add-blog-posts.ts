  try {
    for (let i = 0; i < blogPosts.length; i++) {
      const post = blogPosts[i];
      const slug = generateSlug(post.title);

      // Перевірка чи slug вже існує
      let finalSlug = slug;
      let counter = 1;
      while (true) {
        const existingPost = await prisma.blogPost.findUnique({
          where: { slug: finalSlug },
        });

        if (!existingPost) {
          break;
        }

        finalSlug = `${slug}-${counter}`;
        counter++;
      }

      const createdPost = await prisma.blogPost.create({
        data: {
          title: post.title,
          slug: finalSlug,
          excerpt: post.excerpt,
          content: post.content,
          imageUrl: null,
          published: post.published,
          publishedAt: post.published ? new Date() : null,
        },
      });

      console.log(`✅ Створено статтю ${i + 1}/${blogPosts.length}: "${post.title}"`);
      console.log(`   Slug: ${finalSlug}\n`);
    }

    console.log(`\n🎉 Успішно додано ${blogPosts.length} статей у блог!`);
  } catch (error) {
    console.error("❌ Помилка при додаванні статей:", error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
