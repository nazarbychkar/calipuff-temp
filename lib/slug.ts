/**
 * Генерує URL-friendly slug з тексту (з підтримкою кирилиці)
 * @param text - текст для генерації slug
 * @returns slug в нижньому регістрі з дефісами
 */
export function generateSlug(text: string): string {
  if (!text) return "";

  // Транслітерація кирилиці в латиницю
  let slug = text
    .split("")
    .map((char) => ukrainianToLatin[char] || char)
    .join("");

  // Приведення до нижнього регістру
  slug = slug.toLowerCase();

  // Заміна пробілів та спеціальних символів на дефіси
  slug = slug
    .replace(/[^a-z0-9\s-]/g, "") // Видалення спеціальних символів
    .replace(/\s+/g, "-") // Заміна пробілів на дефіси
    .replace(/-+/g, "-") // Заміна множинних дефісів на один
    .replace(/^-+|-+$/g, ""); // Видалення дефісів на початку та в кінці

  return slug;
}
